async function loadMcaAuditBlocks() {
    const container = document.getElementById("mcaAuditBlocksContainer");
    if (!container) return;
    try {
        const res = await fetch("/api/security/audit-trail");
        const data = await res.json();
        const blocks = data.recent_blocks || [];
        if (!blocks.length) {
            container.innerHTML = `<div class="p-2 text-slate-500">હજુ કોઈ ઓડિટ બ્લોક નથી.</div>`;
            return;
        }
        container.innerHTML = "";
        blocks.forEach(b => {
            const item = document.createElement("div");
            item.className = "p-2 rounded-xl bg-slate-900 border border-slate-800 flex flex-col space-y-0.5 hover:border-amber-500/40 transition";
            item.innerHTML = `
                <div class="flex items-center justify-between">
                    <span class="font-bold text-amber-300">Block #${b.block_index} • ${b.action}</span>
                    <span class="text-slate-500 text-[9px]">${b.timestamp}</span>
                </div>
                <div class="text-slate-400 text-[10px] truncate">${b.details || ''}</div>
                <div class="text-emerald-400/80 text-[9px] truncate">SHA-256: ${b.hash}</div>
            `;
            container.appendChild(item);
        });
    } catch (err) {
        container.innerHTML = `<div class="text-rose-400 text-xs">ઓડિટ બ્લોક લોડ ક્ષતિ: ${err}</div>`;
    }
}

