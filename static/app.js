async function fetchWorldCountries() {
    populateCountryDropdown();
    try {
        const res = await fetch("/api/countries");
        if (res.ok) {
            allWorldCountriesMap = await res.json();
            populateCountryDropdown();
        }
    } catch (err) {
        console.warn("Using standalone country catalog:", err);
    }
}

function populateCountryDropdown() {
    const sel = document.getElementById("countrySelect");
    if (!sel) return;
    sel.innerHTML = "";

    // Sort by name with India first
    const entries = Object.entries(allWorldCountriesMap);
    entries.sort((a, b) => {
        if (a[0] === "IN") return -1;
        if (b[0] === "IN") return 1;
        return a[1].name.localeCompare(b[1].name);
    });

    entries.forEach(([code, data]) => {
        const opt = document.createElement("option");
        opt.value = code;
        opt.textContent = `${data.name} (${data.currency} - ${data.symbol.trim()})`;
        if (code === currentCountry) opt.selected = true;
        sel.appendChild(opt);
    });
}

