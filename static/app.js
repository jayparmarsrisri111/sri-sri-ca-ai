async function postCurrentInvoiceToBooks() {
    if (!currentExtractedInvoice) return;
    const inv = currentExtractedInvoice;
    const je = inv.suggested_journal_entry || {};

    const entryPayload = {
        date: inv.invoice_date || new Date().toISOString().split("T")[0],
        reference_no: inv.invoice_number || `INV-${Date.now()}`,
        description: `${inv.party_name} - ${inv.category}`,
        debit_account: je.debit_account || inv.category,
        credit_account: je.credit_account || "Bank Account",
        amount: inv.subtotal || inv.total_amount,
        tax_account: je.tax_amount > 0 ? (je.tax_account || "Input Tax Credit / Tax Receivable") : null,
        tax_amount: inv.tax_amount || 0,
        category: inv.category,
        country: currentCountry
    };

    try {
        const res = await fetch("/api/transactions", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify(entryPayload)
        });
        const data = await res.json();
        if (data.success) {
            alert("આ બિલની ડબલ-એન્ટ્રી ચોપડામાં સફળતાપૂર્વક થઈ ગઈ છે!");
            currentExtractedInvoice = null;
            document.getElementById("postToBooksBtn").disabled = true;
            document.getElementById("extractedBadge").textContent = "હિસાબમાં નોંધાઈ ગયું ✅";
            loadAllData();
            switchTab("tab-ledger");
        }
    } catch (err) {
        alert("ક્ષતિ: " + err);
    }
}

