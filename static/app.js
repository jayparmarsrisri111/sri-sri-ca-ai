function switchTab(tabId) {
    document.querySelectorAll(".tab-pane").forEach(el => el.classList.add("hidden"));
    document.querySelectorAll(".sidebar-nav-item").forEach(item => item.classList.remove("active"));
    document.querySelectorAll(".mobile-bottom-nav-item").forEach(item => {
        if (item.getAttribute("data-tab") === tabId) {
            item.classList.add("active");
        } else {
            item.classList.remove("active");
        }
    });

    const targetSection = document.getElementById(tabId);
    if (targetSection) targetSection.classList.remove("hidden");

    const activeItem = document.querySelector(`.sidebar-nav-item[data-tab="${tabId}"]`);
    if (activeItem) {
        activeItem.classList.add("active");
        const titleSpan = activeItem.querySelector("span");
        if (titleSpan) {
            document.getElementById("pageTitleDisplay").innerHTML = `${activeItem.querySelector("svg").outerHTML} <span>${titleSpan.textContent}</span>`;
        }
    }

    // Smooth scroll to top on tab switch for mobile users
    window.scrollTo({ top: 0, behavior: "smooth" });

    if (tabId === "tab-tax") refreshTaxData();
    if (tabId === "tab-reconcile") loadReconciliation();
    if (tabId === "tab-reports") loadFinancialReports();
    if (tabId === "tab-clients") loadCAClients();
    if (tabId === "tab-invoicing") loadERPInvoices();
    if (tabId === "tab-inventory") loadERPInventory();
    if (tabId === "tab-payroll") loadERPPayroll();
    if (tabId === "tab-assets") loadERPAssets();
    if (tabId === "tab-anomalies") loadERPAnomalies();
    if (tabId === "tab-udin") loadERPUDIN();
    if (tabId === "tab-superpowers") loadSuperpowersData();
    if (window.lucide) lucide.createIcons();
}

