async function handleAuthFormSubmit(e) {
    e.preventDefault();
    const email = document.getElementById("authEmailInput").value.trim();
    const password = document.getElementById("authPasswordInput").value.trim();

    if (authModalMode === "login") {
        try {
            const res = await fetch("/api/auth/login", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({ email, password })
            });
            const data = await res.json();
            if (data.success) {
                currentUser = data.user;
                updateUserInterfaceForRole();
                document.getElementById("authModal").classList.add("hidden");
                alert("લૉગ ઇન સફળ થયું!");
            } else {
                alert(data.message || "ખોટી વિગતો છે.");
            }
        } catch (err) {
            alert("ક્ષતિ: " + err);
        }
    } else {
        const name = document.getElementById("authNameInput").value.trim();
        const firm = document.getElementById("authFirmInput").value.trim();
        const regNo = document.getElementById("authRegNumberInput").value.trim();

        try {
            const res = await fetch("/api/auth/register", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    name,
                    email,
                    password,
                    role: selectedRoleInModal,
                    company_or_firm_name: firm,
                    membership_or_gstin: regNo
                })
            });
            const data = await res.json();
            if (data.success) {
                currentUser = data.user;
                updateUserInterfaceForRole();
                document.getElementById("authModal").classList.add("hidden");
                alert("રજીસ્ટ્રેશન સફળ થયું!");
            } else {
                alert(data.message || "ક્ષતિ આવી.");
            }
        } catch (err) {
            alert("ક્ષતિ: " + err);
        }
    }
}

